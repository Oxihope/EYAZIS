# -*- coding: utf-8 -*-
"""Окно справки."""

from PyQt6.QtWidgets import (
    QDialog, QVBoxLayout, QTextBrowser, QDialogButtonBox
)


HELP_HTML = """
<h1>Руководство пользователя</h1>

<p>Приложение определяет язык HTML-документа (русский или итальянский)
тремя методами: алфавитным, частотных слов и нейросетевым.</p>

<h2>1. Подготовка данных</h2>
<ul>
  <li><b>Обучающая выборка:</b> положите 10–20 HTML-файлов на русском
      в <code>data/train_ru/</code> и столько же на итальянском
      в <code>data/train_it/</code>.</li>
  <li><b>Тестовые документы:</b> положите HTML-файлы в
      <code>data/test/</code>.</li>
  <li>Размер каждого документа — от 20 до 120 КБ.</li>
</ul>

<h2>2. Запуск</h2>
<ol>
  <li>Нажмите <b>«Обучить»</b> — система построит профили языков.</li>
  <li>Нажмите <b>«Определить язык»</b> — система пройдёт по всем
      тестовым документам и покажет результаты.</li>
  <li>Результаты можно <b>сохранить в CSV</b> или <b>распечатать</b>.</li>
</ol>

<h2>3. Методы</h2>
<ul>
  <li><b>Алфавитный</b> — проверяет, какие буквы (кириллица или латиница)
      преобладают в тексте. Для пары «русский–итальянский» даёт
      100% точности, но бесполезен для двух языков с одинаковым алфавитом.</li>
  <li><b>Частотных слов</b> — строит для каждого языка профиль из
      300 самых частых слов. Сравнивает текст с профилями по
      косинусной мере. Язык с наибольшим сходством считается ответом.</li>
  <li><b>Нейросетевой</b> — MLP-классификатор на символьных 3-граммах.
      Обучается на тех же текстах, что и остальные методы.</li>
</ul>

<h2>4. Метрики</h2>
<p>Для каждой пары методов считается точность (доля правильно
определённых документов) и среднее время определения. Результаты
выводятся в таблице.</p>
"""


class HelpDialog(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Справка")
        self.resize(760, 600)

        lay = QVBoxLayout(self)
        browser = QTextBrowser()
        browser.setHtml(HELP_HTML)
        lay.addWidget(browser)

        bb = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        bb.rejected.connect(self.reject)
        bb.accepted.connect(self.accept)
        lay.addWidget(bb)