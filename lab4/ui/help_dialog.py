# -*- coding: utf-8 -*-
"""Окно справки."""

from PyQt6.QtWidgets import (
    QDialog, QVBoxLayout, QTextBrowser, QDialogButtonBox,
)


HELP_HTML = """
<h1>Руководство пользователя</h1>

<p>Приложение автоматического машинного перевода с английского
на русский язык. Реализован метод <b>прямого пословного перевода</b>
(по классификации систем машинного перевода).</p>

<h2>1. Вкладка «Перевод»</h2>
<ol>
  <li>Нажмите «Загрузить файл» или вставьте английский текст вручную.</li>
  <li>Нажмите «Перевести». Приложение:
    <ul>
      <li>разобьёт текст на предложения;</li>
      <li>определит леммы и части речи через spaCy;</li>
      <li>найдёт переводы в двуязычном словаре;</li>
      <li>склонит русские переводы через pymorphy3;</li>
      <li>соберёт русское предложение.</li>
    </ul>
  </li>
  <li>Ниже появится перевод и статистика:
      общее число слов и число переведённых.</li>
</ol>

<h2>2. Вкладка «Частотный список»</h2>
<p>Список слов с частотами, переводами и грамматической информацией
(POS-тег, расшифровка, часть речи). Упорядочен по убыванию частоты.</p>

<h2>3. Вкладка «Дерево разбора»</h2>
<p>Для выбранного предложения отображается дерево синтаксического
разбора (конституентное), построенное spaCy. Выбор предложения —
в выпадающем списке сверху.</p>

<h2>4. Меню «Словарь»</h2>
<p>Редактор двуязычного словаря: добавление, изменение, удаление
пар «английская лемма — русский перевод». Изменения сохраняются
в JSON-файл.</p>

<h2>5. Экспорт и печать</h2>
<ul>
  <li><b>Ctrl+S</b> — сохранить отчёт в TXT (UTF-8);</li>
  <li><b>Ctrl+P</b> — печать через системный диалог.</li>
</ul>

<h2>6. Возможные проблемы</h2>
<ul>
  <li><b>Модель spaCy не найдена</b> — запустите
      <code>python -m spacy download en_core_web_sm</code>.</li>
  <li><b>Много &lt;слов&gt; в переводе</b> — этих слов нет
      в словаре. Добавьте их через редактор.</li>
  <li><b>Некорректная форма русского слова</b> — добавьте
      перевод в словарь в нужной форме.</li>
</ul>
"""


class HelpDialog(QDialog):
    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Руководство пользователя")
        self.resize(780, 620)
        lay = QVBoxLayout(self)
        browser = QTextBrowser()
        browser.setHtml(HELP_HTML)
        lay.addWidget(browser)
        bb = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        bb.rejected.connect(self.reject)
        bb.accepted.connect(self.accept)
        lay.addWidget(bb)